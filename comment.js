// import подключает чужой код (модуль) в наш файл.
// readLineSync - имя, под которым мы будем использовать библиотеку.
// Обычный JavaScript не умеет остановиться и ждать ввод с клавиатуры,
// а readline-sync умеет: программа замирает, пока пользователь не нажмет Enter.
// Синтаксис import работает, потому что в package.json стоит "type": "module".
import readLineSync from "readline-sync";


// ============================================================
// 1. СОБСТВЕННЫЙ ТИП ОШИБКИ
// ============================================================

// class создает шаблон (класс).
// extends Error означает: наш класс НАСЛЕДУЕТ все от встроенного Error
// (умеет хранить сообщение и стек вызовов), и мы добавляем свое.
// Зачем свой тип: чтобы в catch отличать ОЖИДАЕМЫЕ ошибки
// (пользователь ввел ерунду) от НЕОЖИДАННЫХ (баг в коде).
class ValidationError extends Error {
    // constructor запускается автоматически при new ValidationError("текст").
    // message - текст ошибки, который мы передаем при создании.
    constructor(message) {
        // super(...) вызывает конструктор родителя (Error) и передает ему текст.
        // Благодаря этому потом работает error.message.
        // В наследующих классах super(...) обязателен до обращения к this.
        super(message);

        // this - создаваемый объект ошибки. Записываем в него поле name.
        // Важно: это СТРОКА (в кавычках), а не сам класс.
        // Без этой строки имя было бы просто "Error".
        this.name = "ValidationError";
    }
}


