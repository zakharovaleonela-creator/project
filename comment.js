// 4. ГЛАВНОЕ МЕНЮ
// ============================================================

// Бесконечный цикл: условие true всегда истинно,
// выйти можно только через break.
while (true) {
    // Печать меню. console.log("") дает пустую строку для читаемости.
    console.log("");
    console.log("=== Облік витрат ===");
    console.log("1 - Додати витрату");
    console.log("2 - Показати всі");
    console.log("3 - Пошук за назвою");
    console.log("4 - Топ-3 найбільші");
    console.log("5 - Звіт за категоріями");
    console.log("6 - Видалити");
    console.log("0 - Вийти");

    // Выбор читаем как СТРОКУ (question всегда возвращает строку).
    // const внутри цикла - нормально: на каждой итерации создается новая переменная.
    const choice = readLineSync.question("Ваш вибір: ").trim();

    // Все, что может выбросить ValidationError, обернуто в try.
    // Если внутри случится throw, выполнение сразу перескочит в catch.
    try {
        // Сравниваем со СТРОКАМИ "1", "2"... потому что choice - строка.
        // === не приводит типы, так что "1" === 1 было бы false.
        if (choice === "1") {
            addExpense();
        } else if (choice === "2") {
            showAll();
        } else if (choice === "3") {
            searchByTitle();
        } else if (choice === "4") {
            showTop3();
        } else if (choice === "5") {
            categoryReport();
        } else if (choice === "6") {
            deleteExpense();
        } else if (choice === "0") {
            console.log("До побачення");
            // break выходит из while. Работает именно потому, что мы используем
            // if / else if: внутри switch такой break вышел бы только из switch.
            break;
        } else {
            // Все остальное: пользователь ввел что-то не из меню.
            console.log("Невідомий пункт меню");
        }
    } catch (error) {
        // error - это объект, созданный через new ValidationError(...).
        // instanceof проверяет, что ошибка именно нашего типа.
        if (error instanceof ValidationError) {
            // Ожидаемая ошибка: показываем пользователю понятный текст.
            console.log("Помилка: " + error.message);
        } else {
            // Неожиданная ошибка (баг в коде): сообщаем отдельно.
            console.log("Неочікувана помилка: " + error.message);
        }
        // После catch цикл идет дальше и снова показывает меню,
        // поэтому программа не завершается из-за неверного ввода.
    }
}