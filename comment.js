// Массив всех расходов. Каждый элемент - объект вида
// { title: "кава", amount: 55, category: "їжа" }.
// const запрещает ПЕРЕПРИСВОИТЬ переменную (expenses = ...),
// но содержимое массива менять можно (push, splice).
// Нам именно это и нужно, поэтому const подходит.
const expenses = [];


// ============================================================
// 3. ФУНКЦИИ
// ============================================================

// СТРЕЛОЧНАЯ функция: принимает число и возвращает строку для вывода.
// (value) - параметр, => - стрелка, дальше тело.
// У стрелочной функции из одного выражения return не нужен:
// результат возвращается автоматически.
// toFixed(2) округляет до двух знаков и возвращает СТРОКУ: 55 -> "55.00".
// + " грн" склеивает строку с валютой: "55.00 грн".
// Объявлена через const, поэтому ее нельзя вызвать ДО этой строки,
// поэтому она стоит выше всех мест, где используется.
// Форматируем только при выводе: в объекте всегда хранится ЧИСЛО,
// иначе reduce и sort будут работать неправильно.
const formatMoney = (value) => value.toFixed(2) + " грн";


// Читает непустую строку (название, категория).
// question - текст вопроса, который увидит пользователь.
function readNonEmpty(question) {
    // Выполняется справа налево:
    // 1) readLineSync.question(question) печатает вопрос, ждет ввод
    //    и ВСЕГДА возвращает строку (даже если ввели цифры);
    // 2) .trim() убирает пробелы в начале и в конце;
    // 3) результат сохраняется в text.
    const text = readLineSync.question(question).trim();

    // === - строгое сравнение (без приведения типов).
    // Если после trim() ничего не осталось, значит ввели пустоту или одни пробелы.
    if (text === "") {
        // throw выбрасывает ошибку и СРАЗУ прерывает функцию:
        // код ниже не выполнится, управление уйдет в ближайший catch.
        throw new ValidationError("Поле не може бути порожнім");
    }

    // Ошибки не было - возвращаем очищенную строку тому, кто вызвал функцию.
    return text;
}


// Читает сумму и возвращает ЧИСЛО больше нуля.
function readAmount(question) {
    // raw - "сырой" ввод пользователя без пробелов по краям.
    const raw = readLineSync.question(question).trim();

    // Отдельная проверка на пустоту нужна, потому что Number("") дает 0,
    // а не NaN. Без нее пустой ввод превратился бы в ноль.
    if (raw === "") {
        throw new ValidationError("Сума не може бути порожньою");
    }

    // replace(",", ".") заменяет запятую на точку, чтобы "23000,25" тоже работало
    // (в Украине дробные числа часто пишут через запятую).
    // Number(...) превращает строку в число:
    // "55" -> 55, "12.5" -> 12.5, "abc" -> NaN (не число).
    const value = Number(raw.replace(",", "."));

    // Number.isNaN(value) возвращает true, если value - это NaN.
    // Писать value === NaN нельзя: NaN не равно даже самому себе,
    // такая проверка всегда была бы false.
    if (Number.isNaN(value)) {
        throw new ValidationError("Сума повинна бути числом");
    }

    // Отсекаем ноль и отрицательные суммы.
    // Здесь <=, а не ===, потому что нужен диапазон, а не точное совпадение.
    if (value <= 0) {
        throw new ValidationError("Сума повинна бути більшою за нуль");
    }

    // Возвращаем именно ЧИСЛО, а не строку: если сохранить "55",
    // то reduce начнет склеивать строки ("0" + "55") вместо сложения.
    return value;
}


// Добавляет новый расход в массив (пункт меню 1).
function addExpense() {
    // Три вопроса по очереди. Если любая из функций чтения бросит throw,
    // addExpense прервется, и неполная запись НЕ добавится.
    const title = readNonEmpty("Введіть назву: ");
    const amount = readAmount("Введіть суму: ");

    // toLowerCase() переводит категорию в нижний регистр, чтобы
    // "Їжа" и "їжа" не считались двумя разными категориями в отчете.
    const category = readNonEmpty("Введіть категорію: ").toLowerCase();

    // Создаем объект (запись). Запись { title, amount, category } -
    // сокращение от { title: title, amount: amount, category: category }.
    // Если имя поля совпадает с именем переменной, его можно писать один раз.
    const expense = { title, amount, category };

    // push добавляет элемент в КОНЕЦ массива.
    expenses.push(expense);

    console.log("Витрату додано");
}


// Показывает список расходов (пункт меню 2, а также результаты поиска и топ-3).
// list = expenses - параметр СО ЗНАЧЕНИЕМ ПО УМОЛЧАНИЮ:
// showAll() без аргумента покажет все расходы,
// showAll(found) покажет то, что мы передали.
// Так одна функция используется в нескольких местах.
function showAll(list = expenses) {
    // length - количество элементов в массиве.
    if (list.length === 0) {
        console.log("Список порожній");
        // return; без значения просто завершает функцию,
        // чтобы код ниже не выполнялся.
        return;
    }

    // forEach перебирает массив и для КАЖДОГО элемента вызывает функцию,
    // которую мы ему передали. Такая функция называется CALLBACK
    // (функция обратного вызова).
    // e - текущий элемент (запись), i - его индекс (0, 1, 2...).
    list.forEach((e, i) => {
        // Строка в обратных кавычках (бектиках) - шаблонная.
        // Внутри ${...} можно вставлять любые выражения.
        // i + 1, потому что индексы с нуля, а пользователю удобнее с единицы.
        // e.title, e.category - обращение к полям объекта через точку.
        // Пример вывода: 1. кава - 55.00 грн (їжа)
        console.log(`${i + 1}. ${e.title} - ${formatMoney(e.amount)} (${e.category})`);
    });
}


// Поиск по названию без учета регистра (пункт меню 3).
function searchByTitle() {
    // Читаем непустой запрос и сразу приводим к нижнему регистру.
    const query = readNonEmpty("Введіть назву для пошуку: ").toLowerCase();

    // filter проходит по массиву и оставляет ТОЛЬКО те элементы,
    // для которых callback вернул true. Исходный массив не меняется,
    // создается новый.
    // e.title.toLowerCase() - название записи в нижнем регистре.
    // includes(query) проверяет, содержится ли запрос внутри строки.
    // Приводим к нижнему регистру ОБЕ стороны, поэтому регистр не важен.
    const found = expenses.filter((e) => e.title.toLowerCase().includes(query));

    if (found.length === 0) {
        console.log("Нічого не знайдено");
        return;
    }

    // Переиспользуем showAll, передавая ему только найденное.
    showAll(found);
}


// Показывает 3 самых больших расхода (пункт меню 4).
function showTop3() {
    // slice() без аргументов делает КОПИЮ массива.
    // Это обязательно: sort меняет массив НА МЕСТЕ,
    // и без копии мы бы испортили порядок в expenses.
    const sorted = expenses.slice();

    // sort принимает функцию-сравнение, которая получает два элемента a и b
    // и возвращает число:
    //   отрицательное -> a ставится перед b
    //   положительное -> b ставится перед a
    //   ноль          -> порядок не меняется
    // b.amount - a.amount: если у b сумма больше, результат положительный,
    // и b идет раньше. Получается сортировка от большего к меньшему.
    // (a.amount - b.amount дало бы сортировку по возрастанию.)
    sorted.sort((a, b) => b.amount - a.amount);

    // slice(0, 3) вырезает элементы с индексами 0, 1, 2 (конец не включается).
    // Если записей меньше трех, вернется сколько есть, без ошибки.
    showAll(sorted.slice(0, 3));
}


// Отчет по категориям (пункт меню 5): сумма по каждой категории и общий итог.
function categoryReport() {
    if (expenses.length === 0) {
        console.log("Список порожній");
        return;
    }

    // reduce "сворачивает" массив в одно значение.
    // Callback получает:
    //   acc - аккумулятор (то, что накоплено на прошлых шагах)
    //   e   - текущий элемент
    // Второй аргумент reduce ({}) - НАЧАЛЬНОЕ значение аккумулятора.
    // Здесь сворачиваем в объект вида { категория: сумма }.
    const totals = expenses.reduce((acc, e) => {
        // acc[e.category] - обращение к полю по имени из переменной
        // (квадратные скобки, а не точка).
        // Если категория встретилась впервые, acc[e.category] равно undefined.
        // Оператор || берет правое значение, если левое "пустое",
        // поэтому (undefined || 0) дает 0.
        // К этому прибавляем сумму текущей записи и записываем обратно.
        acc[e.category] = (acc[e.category] || 0) + e.amount;

        // Callback обязан вернуть аккумулятор для следующего шага.
        return acc;
    }, {});

    // Object.keys(totals) возвращает массив ключей объекта (названия категорий).
    // Перебираем их через forEach (еще один callback).
    // totals[category] достает сумму по ключу.
    Object.keys(totals).forEach((category) => {
        console.log(`${category}: ${formatMoney(totals[category])}`);
    });

    // Второй reduce: начальное значение 0, на каждом шаге sum + e.amount.
    // Это общая сумма всех расходов.
    const total = expenses.reduce((sum, e) => sum + e.amount, 0);
    console.log(`Разом: ${formatMoney(total)}`);
}


// Удаляет расход по номеру из списка (пункт меню 6).
function deleteExpense() {
    if (expenses.length === 0) {
        console.log("Список порожній");
        return;
    }

    // Показываем список, чтобы пользователь видел номера.
    showAll();

    const raw = readLineSync.question("Введіть номер для видалення: ").trim();
    const number = Number(raw);

    // || означает "или": ошибка, если выполнено хотя бы одно условие.
    //   raw === ""                 - пустой ввод (иначе Number("") стал бы 0)
    //   Number.isNaN(number)       - не число
    //   !Number.isInteger(number)  - не целое (! означает "не"), например 1.5
    if (raw === "" || Number.isNaN(number) || !Number.isInteger(number)) {
        throw new ValidationError("Номер повинен бути цілим числом");
    }

    // Проверка диапазона: допустимы номера от 1 до количества записей.
    if (number < 1 || number > expenses.length) {
        throw new ValidationError("Немає запису з таким номером");
    }

    // splice(начало, сколько) удаляет элементы ИЗ САМОГО массива.
    // number - 1 переводит номер для пользователя (с 1) в индекс (с 0).
    // 1 значит "удалить один элемент".
    expenses.splice(number - 1, 1);
    console.log("Витрату видалено");
}


